#!/usr/bin/env python3
"""Read and write claude-bot status comments (and phase labels) from scripts.

Every issue the bot handles has one status comment whose first line is
`<!-- claude-bot:status {json} -->`. This is the one place that edits it from
bin/: dispatch.py and plan.py use it as a library, the orchestrator uses the CLI
instead of hand-written JSON patches.

Writes go through `gh api`. In cloud sessions a proxy rewrites bodies sent that
way: a bare https://claude.ai/... URL gets a backtick put in front of it, which
breaks the JSON. Two forms survive, so every write uses them:
  - in the JSON line, URLs are written `https:\\/\\/...` (valid JSON, parses back
    to the same string);
  - in the human part, bare claude.ai URLs become markdown links.
After each write the comment is read back; a body that no longer parses or a
JSON value that changed is reported as an error (exit 1).

Usage:
  bin/status.py get   o/r#n
  bin/status.py patch o/r#n [--phase P] [--set key=JSON ...] [--unset key ...]
                            [--note TEXT ...] [--dry-run]
  bin/status.py label o/r#n [--add L ...] [--remove L ...]

--set values are JSON (`--set pr=31`, `--set 'slot="quick"'`,
`--set 'parallel={"with":[3],"ok":true}'`); a value that isn't valid JSON is
taken as a string. --phase also swaps the claude:<phase> label (only phase
labels: claude, claude:next/paused/ping, model:*, effort:*, lane:quick and
every other label stay) and rewrites the heading. --note adds a line to the
human part (e.g. "⚠️ Run: ...") unless it's already there.
"""
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

STATUS_RE = re.compile(r"<!-- claude-bot:status (\{.*?\}) -->", re.S)
STATUS_MARKER = "<!-- claude-bot:status"
BOT_MARKER = "<!-- claude-bot"
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# Phase labels are claude:<phase>; these claude: labels are the owner's, not phases.
OWNER_LABELS = {"claude:next", "claude:paused", "claude:ping"}
# The label each phase carries. dispatching carries claude:designing (the tick
# adds it at dispatch so the issue leaves the queue at once); queued and
# cancelled carry none.
PHASE_LABEL = {
    "queued": None,
    "dispatching": "claude:designing",
    "designing": "claude:designing",
    "needs-input": "claude:needs-input",
    "approved": "claude:approved",
    "building": "claude:building",
    "in-review": "claude:in-review",
    "blocked": "claude:blocked",
    "done": "claude:done",
    "cancelled": None,
}
HEADINGS = {
    "queued": "⏳ Queued",
    "dispatching": "🚀 Dispatching",
    "designing": "✏️ Designing",
    "needs-input": "❓ Waiting for your input{on}",
    "approved": "✅ Approved — waiting for a build slot",
    "building": "🔨 Building",
    "in-review": "👀 Ready for review{on}",
    "blocked": "⛔ Blocked",
    "done": "🎉 Merged",
    "cancelled": "🚫 Cancelled",
}


def now_stamp():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")


def parse_ref(ref):
    """'owner/repo#12' -> ('owner/repo', 12)."""
    match = re.fullmatch(r"([\w.-]+/[\w.-]+)#(\d+)", ref.strip())
    if not match:
        raise SystemExit(f"bad issue reference {ref!r}: expected owner/repo#N")
    return match.group(1), int(match.group(2))


def gh(*args, body=None):
    """Call `gh api`; body (a dict) is sent as the JSON request body."""
    command = ["gh", "api", *args]
    if body is not None:
        command += ["--input", "-"]
    result = subprocess.run(command, input=json.dumps(body) if body is not None else None,
                            capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"gh api {' '.join(args)}: {(result.stderr or result.stdout).strip()}")
    return json.loads(result.stdout) if result.stdout.strip() else None


def issue_comments(repo, number):
    comments, page = [], 1
    while True:
        batch = gh(f"repos/{repo}/issues/{number}/comments?per_page=100&page={page}")
        comments += batch
        if len(batch) < 100:
            return comments
        page += 1


def parse_body(body):
    """Status dict from a status comment body (None if it isn't one)."""
    if not (body or "").startswith(STATUS_MARKER):
        return None
    match = STATUS_RE.match(body)
    return json.loads(match.group(1)) if match else None


def find(repo, number, comments=None):
    """(comment_id, status, body) of the issue's status comment, or (None, None, None)."""
    for comment in comments if comments is not None else issue_comments(repo, number):
        body = comment.get("body") or ""
        if body.startswith(STATUS_MARKER):
            return comment["id"], parse_body(body), body
    return None, None, None


def json_line(status):
    text = json.dumps(status, ensure_ascii=False, separators=(",", ":"))
    # `https:\/\/` is the same string to any JSON parser, and the proxy leaves it alone.
    text = text.replace("://", ":\\/\\/")
    return f"<!-- claude-bot:status {text} -->"


def safe_human(text):
    """Bare claude.ai URLs -> markdown links (the proxy mangles bare ones)."""
    text = re.sub(r"Live session: (https://claude\.ai/\S+)", r"[Live session](\1)", text)
    return re.sub(r"(?<![(\[<`])(https://claude\.ai/code/\S*session_[\w-]+)", r"[session](\1)", text)


def heading(status):
    phase = status.get("phase") or "queued"
    on = f" on #{status['pr']}" if status.get("pr") else ""
    return "### 🤖 claude-bot · " + HEADINGS.get(phase, phase).format(on=on)


def checklist(status):
    phase = status.get("phase") or "queued"
    reached = {
        "queued": 0, "dispatching": 0, "designing": 0, "needs-input": 1, "approved": 2,
        "building": 2, "in-review": 3, "done": 4,
    }.get(phase, 0)
    pr = status.get("pr")
    design = "Design discussion" + (f": #{pr}" if pr and status.get("design") == "pr" else "")
    if status.get("design") == "skipped":
        design = "Design discussion (skipped: plan on the issue)"
    lines = ["Queued", design, "Ready to build", "Built — playable preview" + (f" on #{pr}" if pr else ""), "Merged"]
    return "\n".join(f"- [{'x' if i <= reached else ' '}] {text}" for i, text in enumerate(lines))


def render(status, notes=()):
    """A whole new status comment body (used when there is none yet)."""
    session = status.get("session_url")
    lines = [json_line(status), heading(status), "", checklist(status), ""]
    lines += list(notes)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    tail = f"[Live session]({session}) · Updated {stamp}" if session else f"Starting a worker session… · Updated {stamp}"
    lines.append(tail)
    return safe_human("\n".join(lines)) + "\n" + FOOTER


def rebuild(body, status, phase_changed=False, notes=()):
    """Replace the JSON line of an existing body, keeping the human part as the
    worker wrote it; with phase_changed, also the heading and the standard
    checklist ticks. notes are added before the 'Live session'/'Updated' line."""
    _, _, rest = body.partition("\n")
    lines = rest.split("\n")
    if phase_changed:
        lines = [heading(status) if line.startswith("### 🤖 claude-bot") else line for line in lines]
        if status.get("phase") == "done":
            lines = [re.sub(r"^- \[ \] (Merged|Built)", r"- [x] \1", line) for line in lines]
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [re.sub(r"Updated \d{4}-\d\d-\d\d \d\d:\d\d UTC", f"Updated {stamp}", line) for line in lines]
    if status.get("session_url"):
        lines = [f"[Live session]({status['session_url']}) · Updated {stamp}"
                 if line.startswith("Starting a worker session…") else line for line in lines]
    new = [n for n in notes if n not in lines]
    if new:
        at = next((i for i, line in enumerate(lines)
                   if "Live session" in line or line.startswith("Starting a worker session") or line.startswith("---")),
                  len(lines))
        lines[at:at] = new
    return json_line(status) + "\n" + safe_human("\n".join(lines))


def verify(written, status):
    got = parse_body(written.get("body") or "")
    if got != status:
        raise RuntimeError("status comment read back differently than written "
                           f"(proxy mangling?): {json.dumps(got)[:300]}")
    if "`https://claude.ai" in written["body"]:
        raise RuntimeError("a claude.ai URL came back wrapped in a backtick")


def write(repo, comment_id, body, status):
    written = gh("-X", "PATCH", f"repos/{repo}/issues/comments/{comment_id}", body={"body": body})
    verify(written, status)
    return written


def create(repo, number, body, status):
    written = gh("-X", "POST", f"repos/{repo}/issues/{number}/comments", body={"body": body})
    verify(written, status)
    return written


def set_labels(repo, number, add=(), remove=()):
    """Add/remove single labels; never touches the others."""
    current = [label["name"] for label in gh(f"repos/{repo}/issues/{number}/labels?per_page=100")]
    for name in remove:
        if name in current:
            gh("-X", "DELETE", f"repos/{repo}/issues/{number}/labels/{name}")
    missing = [name for name in add if name not in current]
    if missing:
        gh("-X", "POST", f"repos/{repo}/issues/{number}/labels", body={"labels": missing})


def phase_label_changes(labels, phase):
    """(add, remove) to make `labels` carry exactly the phase label for `phase`."""
    want = PHASE_LABEL.get(phase)
    phase_labels = [l for l in labels if l.startswith("claude:") and l not in OWNER_LABELS]
    remove = [l for l in phase_labels if l != want]
    add = [want] if want and want not in labels else []
    return add, remove


def patch(repo, number, changes=None, unset=(), phase=None, notes=(), dry_run=False, found=None, labels=None):
    """Merge changes into the status JSON (and swap the phase label when phase
    is given). Returns the new body. `found` = (comment_id, status, body) if
    the caller already has it; `labels` = the issue's current labels."""
    comment_id, status, body = found or find(repo, number)
    if comment_id is None:
        raise RuntimeError(f"{repo}#{number} has no status comment")
    new = dict(status or {})
    new.update(changes or {})
    for key in unset:
        new.pop(key, None)
    if phase:
        new["phase"] = phase
    new["updated"] = now_stamp()
    text = rebuild(body, new, phase_changed=bool(phase and phase != (status or {}).get("phase")), notes=notes)
    if dry_run:
        return text
    write(repo, comment_id, text, new)
    if phase:
        if labels is None:
            labels = [label["name"] for label in gh(f"repos/{repo}/issues/{number}/labels?per_page=100")]
        add, remove = phase_label_changes(labels, phase)
        if add or remove:
            set_labels(repo, number, add, remove)
    return text


def parse_value(text):
    try:
        return json.loads(text)
    except ValueError:
        return text


def main(argv):
    if not argv or argv[0] in ("-h", "--help") or len(argv) < 2:
        print(__doc__)
        return 0 if argv and argv[0] in ("-h", "--help") else 2
    command, ref, rest = argv[0], argv[1], argv[2:]
    repo, number = parse_ref(ref)
    if command == "get":
        comment_id, status, _ = find(repo, number)
        print(json.dumps({"comment_id": comment_id, "status": status}, indent=1, ensure_ascii=False))
        return 0 if comment_id else 1
    if command == "label":
        add, remove, i = [], [], 0
        while i < len(rest):
            (add if rest[i] == "--add" else remove).append(rest[i + 1])
            i += 2
        set_labels(repo, number, add, remove)
        print(f"{repo}#{number}: +{add} -{remove}")
        return 0
    if command != "patch":
        print(__doc__)
        return 2
    changes, unset, notes, phase, dry_run, i = {}, [], [], None, False, 0
    while i < len(rest):
        flag = rest[i]
        if flag == "--dry-run":
            dry_run = True
            i += 1
            continue
        value = rest[i + 1]
        if flag == "--set":
            key, _, raw = value.partition("=")
            changes[key] = parse_value(raw)
        elif flag == "--unset":
            unset.append(value)
        elif flag == "--note":
            notes.append(value)
        elif flag == "--phase":
            if value not in PHASE_LABEL:
                raise SystemExit(f"unknown phase {value!r}")
            phase = value
        else:
            raise SystemExit(f"unknown option {flag}")
        i += 2
    text = patch(repo, number, changes, unset, phase, notes, dry_run)
    if dry_run:
        print(text)
    else:
        print(f"patched {repo}#{number}" + (f" -> {phase}" if phase else ""))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except RuntimeError as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
